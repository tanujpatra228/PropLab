"""Convert NeuralFoil network weights into src/physics/neuralfoil/weights.js.

Usage:
    pip install neuralfoil
    python scripts/export-neuralfoil.py [model_size]   # default: large

Only the first 6 network outputs are kept (confidence, CL, CD, CM, Top_Xtr, Bot_Xtr);
PropLab does not use the boundary-layer outputs, so their rows of the last layer are dropped.
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np
import neuralfoil

size = sys.argv[1] if len(sys.argv) > 1 else "large"
wdir = Path(neuralfoil.__file__).parent / "nn_weights_and_biases"
d = np.load(wdir / f"nn-{size}.npz")
dist = np.load(wdir / "scaled_input_distribution.npz")

idx = sorted({int(k.split(".")[1]) for k in d.keys()})
layers, buf = [], []
for j, i in enumerate(idx):
    W = d[f"net.{i}.weight"].astype(np.float32)
    b = d[f"net.{i}.bias"].astype(np.float32)
    if j == len(idx) - 1:
        W, b = W[:6], b[:6]
    layers.append([int(W.shape[0]), int(W.shape[1])])
    buf += [W.ravel(), b.ravel()]
buf += [dist["mean_inputs_scaled"].astype(np.float32), dist["inv_cov_inputs_scaled"].astype(np.float32).ravel()]
raw = np.concatenate(buf).astype("<f4").tobytes()

out = Path(__file__).resolve().parent.parent / "src/physics/neuralfoil/weights.js"
out.write_text(
    f'// NeuralFoil "{size}" network weights (MIT License, (c) Peter Sharpe), converted for PropLab.\n'
    f"// Source: https://github.com/peterdsharpe/NeuralFoil  (neuralfoil {getattr(neuralfoil, '__version__', '?')}, nn-{size}.npz)\n"
    "// Output layer trimmed to the first 6 outputs: confidence, CL, CD, CM, Top_Xtr, Bot_Xtr.\n"
    "// Layout (float32, little-endian): for each layer W (rows x cols, row-major) then b (rows);\n"
    "// then mean_inputs_scaled (25) and inv_cov_inputs_scaled (25 x 25).\n"
    "// Generated by scripts/export-neuralfoil.py. Do not edit by hand.\n"
    f"export const LAYERS = {json.dumps(layers)};\n"
    f"export const DATA = '{base64.b64encode(raw).decode()}';\n"
)
print(f"wrote {out} ({len(raw)} bytes of weights)")
